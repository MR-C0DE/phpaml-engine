import {execFileSync} from 'node:child_process';
import {viewFile, engineTag} from './test-environment.mjs';
import {expect, test} from './runtime-test.mjs';

const sample = JSON.parse(execFileSync(process.env.PHP_BINARY || 'php', [viewFile('tests/reactive-styles.php'), '--json'], {encoding: 'utf8'}));

test('State drives every Style form without replacing DOM, leaking scope or accumulating CSS', async ({page}) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/reactive-styles', route => route.fulfill({contentType: 'text/html', body: `<!doctype html><main data-aml-client>${sample.html}</main>${engineTag}`}));
  await page.goto('/reactive-styles');
  await expect(page.locator('main')).toHaveAttribute('data-aml-engine-mounted', 'true');
  const sheetCount = await page.locator('style[data-aml-style]').count();
  await expect(page.locator('#reactive-direct')).toHaveCSS('font-size', '24px');
  await page.evaluate(() => { window.styleNode = document.getElementById('reactive-direct'); window.styleErrors = []; document.querySelector('main').addEventListener('aml:render-error', e => window.styleErrors.push(e.detail.error.message)); });
  await page.locator('#change-style').click();
  for (const id of ['reactive-direct', 'reactive-inline', 'reactive-named', 'reactive-mixed', 'reactive-map', 'reactive-helper', 'reactive-explicit', 'reactive-module', 'reactive-child', 'reactive-ref-map']) await expect(page.locator(`#${id}`)).toHaveCSS('color', 'rgb(220, 38, 38)');
  for (const [id, size] of Object.entries({'reactive-direct':32, 'reactive-inline':33, 'reactive-named':32, 'reactive-mixed':32, 'reactive-alias':35, 'reactive-helper':34, 'reactive-closure':36, 'reactive-module':32, 'reactive-child':32, 'reactive-closure-map':37, 'reactive-arguments':32})) await expect(page.locator(`#${id}`)).toHaveCSS('font-size', `${size}px`);
  await expect(page.locator('#reactive-snapshot')).toHaveCSS('font-size', '31px');
  await expect(page.locator('#reactive-static-closure')).toHaveCSS('font-size', '25px');
  await expect(page.locator('#reactive-direct')).toHaveCSS('font-weight', '700');
  for (const id of ['reactive-direct', 'reactive-mixed', 'shared-a', 'shared-b']) await expect(page.locator(`#${id}`)).toHaveCSS('padding-top', '20px');
  await expect(page.locator('#reactive-map')).toHaveCSS('padding-top', '21px');
  await expect(page.locator('#reactive-template')).toHaveCSS('border-top-color', 'rgb(220, 38, 38)');
  for (const id of ['reactive-template', 'reactive-php', 'reactive-legacy']) await expect(page.locator(`#${id}`)).toHaveCSS('width', '32px');
  await expect(page.locator('#reactive-concat')).toHaveCSS('width', '64px');
  for (const id of ['reactive-other', 'reactive-static']) await expect(page.locator(`#${id}`)).toHaveCSS('color', 'rgb(112, 71, 235)');
  await expect(page.locator('#shared-a')).toHaveCSS('background-color', 'rgb(220, 38, 38)');
  await page.locator('#shared-a').hover();
  await expect(page.locator('#shared-a')).toHaveCSS('background-color', 'rgb(112, 71, 235)');
  await expect(page.locator('#shared-b')).toHaveCSS('background-color', 'rgb(220, 38, 38)');
  await page.setViewportSize({width:375, height:812});
  await expect(page.locator('#shared-b')).toHaveCSS('padding-top', '10px');
  await page.locator('#reveal-style').click();
  await expect(page.locator('#reactive-conditional')).toHaveCSS('font-size', '32px');
  await expect(page.locator('#reactive-conditional')).toHaveCSS('color', 'rgb(220, 38, 38)');
  await page.locator('.counter-grow').first().click();
  await expect(page.locator('.counter-text').first()).toHaveCSS('font-size', '22px');
  await expect(page.locator('.counter-text').last()).toHaveCSS('font-size', '20px');
  expect(await page.evaluate(() => window.styleNode === document.getElementById('reactive-direct'))).toBe(true);
  expect(await page.evaluate(() => window.styleErrors)).toEqual([]);
  await page.locator('#invalid-style').click();
  await expect.poll(() => page.evaluate(() => window.styleErrors.length)).toBeGreaterThan(0);
  await expect(page.locator('#reactive-direct')).toHaveCSS('color', 'rgb(220, 38, 38)');
  await page.locator('#recover-style').click();
  await expect(page.locator('#reactive-direct')).toHaveCSS('color', 'rgb(0, 128, 0)');
  await expect(page.locator('#reactive-conditional')).toHaveCSS('color', 'rgb(0, 128, 0)');
  await expect(page.locator('style[data-aml-style]')).toHaveCount(sheetCount);
  expect(errors).toEqual([]);
});
