export async function verifyStyleFinalization(page, expect) {
  const sheets = await page.locator('style[data-aml-style]').count();
  await page.evaluate(() => {
    window.finalStyleNode = document.getElementById('final-priority'); window.finalStyleErrors = [];
    document.addEventListener('aml:render-error', event => window.finalStyleErrors.push(event.detail.error.message), true);
  });
  const beforeColor = () => page.locator('#final-pseudo').evaluate(node => getComputedStyle(node, '::before').color);
  await expect(page.locator('#final-priority')).toHaveCSS('color', 'rgb(255, 0, 0)');
  await expect(page.locator('#final-priority')).toHaveCSS('width', '140px');
  await expect(page.locator('#final-order')).toHaveCSS('padding-left', '33px');
  const initialColor = await page.locator('#final-initial-reference').evaluate(node => getComputedStyle(node).color);
  await expect(page.locator('#final-initial-binding')).toHaveCSS('color', initialColor);
  await expect.poll(beforeColor).toBe('rgb(255, 0, 0)');
  await expect.poll(() => page.locator('#final-literal').evaluate(node => getComputedStyle(node, '::before').content)).toBe('"$1 !important"');
  await page.locator('#final-normal').click();
  await expect(page.locator('#final-priority')).toHaveCSS('color', 'rgb(0, 0, 255)');
  await expect(page.locator('#final-plain')).toHaveCSS('color', 'rgb(0, 128, 0)');
  await expect(page.locator('#final-priority')).toHaveCSS('width', '32px');
  await expect(page.locator('#final-order')).toHaveCSS('padding-left', '12px');
  await expect(page.locator('#final-default')).toHaveCSS('padding-left', '7px');
  await page.locator('#final-reset').click();
  await expect(page.locator('#final-priority')).toHaveCSS('color', initialColor);
  await expect(page.locator('#final-plain')).toHaveCSS('color', initialColor);
  await expect.poll(beforeColor).toBe(initialColor);
  await expect(page.locator('#final-order')).toHaveCSS('padding-left', '0px');
  await page.locator('#final-inherit').click();
  await expect(page.locator('#final-priority')).toHaveCSS('color', 'rgb(128, 0, 128)');
  await expect.poll(beforeColor).toBe('rgb(128, 0, 128)');
  await page.locator('#final-normal').click();
  await expect(page.locator('#final-plain')).toHaveCSS('color', 'rgb(0, 128, 0)');
  await expect.poll(beforeColor).toBe('rgb(0, 0, 255)');
  await page.locator('#final-important').click();
  await expect(page.locator('#final-priority')).toHaveCSS('color', 'rgb(0, 128, 0)');
  await expect(page.locator('#final-priority')).toHaveCSS('width', '48px');
  await expect(page.locator('#final-default')).toHaveCSS('padding-left', '10px');
  await expect.poll(beforeColor).toBe('rgb(0, 128, 0)');
  expect(await page.evaluate(() => window.finalStyleErrors)).toEqual([]);
  await page.locator('#final-invalid').click();
  await expect.poll(() => page.evaluate(() => window.finalStyleErrors.length)).toBeGreaterThan(0);
  const errorCount = await page.evaluate(() => window.finalStyleErrors.length);
  await expect(page.locator('#final-priority')).toHaveCSS('color', 'rgb(0, 128, 0)');
  await expect(page.locator('#final-priority')).toHaveCSS('width', '64px');
  await page.locator('#final-unrelated').click();
  expect(await page.evaluate(() => window.finalStyleErrors.length)).toBe(errorCount);
  await page.locator('#final-empty').click();
  await expect(page.locator('#final-priority')).toHaveCSS('width', '140px');
  await expect(page.locator('#final-priority')).toHaveCSS('color', 'rgb(0, 0, 255)');
  await expect(page.locator('#final-plain')).toHaveCSS('color', 'rgb(128, 0, 128)');
  await expect(page.locator('#final-order')).toHaveCSS('padding-left', '33px');
  await expect(page.locator('#final-default')).toHaveCSS('padding-left', '7px');
  await page.locator('#final-normal').click();
  await expect(page.locator('#final-plain')).toHaveCSS('color', 'rgb(0, 128, 0)');
  expect(await page.evaluate(() => window.finalStyleNode === document.getElementById('final-priority'))).toBe(true);
  await expect(page.locator('style[data-aml-style]')).toHaveCount(sheets);
}
