import {execFileSync} from 'node:child_process';
import {viewFile, engineTag, taskBaseURL} from './test-environment.mjs';
import {expect, test} from './runtime-test.mjs';

const sample = JSON.parse(execFileSync(process.env.PHP_BINARY || 'php', [viewFile('tests/controls.php'), '--json'], {encoding: 'utf8'}));
test('Picker Toggle and Calendar preserve State, keyboard input, bounds and child forms', async ({page}) => {
  test.setTimeout(60_000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.route('**/controls-fixture', route => route.fulfill({contentType: 'text/html',
    headers: {'Content-Security-Policy': "default-src 'none'; script-src 'self'; style-src 'unsafe-inline'"},
    body: `<!doctype html><html lang="fr"><meta charset="utf-8"><main data-aml-client>${sample.html}</main>${engineTag}</html>`}));
  await page.goto('/controls-fixture');
  await expect(page.locator('main')).toHaveAttribute('data-aml-engine-mounted', 'true');
  const calendar = page.locator('[data-aml-calendar]').filter({has: page.locator('#date')});
  await expect(calendar.getByRole('grid')).toHaveAttribute('aria-label', /février 2028/);
  await expect(calendar.locator('[data-aml-calendar-day="2028-02-26"]')).toBeDisabled();
  await expect(calendar.locator('[data-aml-calendar-day][tabindex="0"]')).toHaveCount(1);
  await page.locator('#country').selectOption('FR');
  await expect(page.locator('#selected-country')).toHaveText('FR');
  await expect(page.locator('[name="child-country"]')).toHaveValue('FR');
  await page.locator('#enabled').check();
  await expect(page.locator('#selected-enabled')).toHaveText('oui');
  await page.locator('#enabled').focus(); await page.keyboard.press('Space');
  await expect(page.locator('[name="child-enabled"]')).not.toBeChecked();
  await calendar.locator('[data-aml-calendar-day="2028-02-29"]').click();
  await expect(page.locator('#selected-date')).toHaveText('2028-02-29');
  await expect(page.locator('#changes')).toHaveText('1');
  await page.keyboard.press('ArrowRight');
  await expect(calendar.locator('[data-aml-calendar-day="2028-03-01"]')).toBeFocused();
  await expect(page.locator('#selected-date')).toHaveText('2028-02-29');
  await page.keyboard.press('Enter');
  await expect(page.locator('#selected-date')).toHaveText('2028-03-01');
  await expect(page.locator('[name="child-date"]')).toHaveValue('2028-03-01');
  await expect(page.locator('#changes')).toHaveText('2');
  await expect(calendar.getByRole('button', {name: 'Mois suivant'})).toBeDisabled();
  await page.getByRole('button', {name: 'Depuis le State'}).click();
  await expect(calendar.getByRole('grid')).toHaveAttribute('aria-label', /février 2028/);
  await page.getByRole('button', {name: 'Verrouiller'}).click();
  await expect(page.locator('#date')).toBeDisabled();
  expect(await calendar.locator('button').evaluateAll(buttons => buttons.every(button => button.disabled))).toBe(true);
  await page.getByRole('button', {name: 'Verrouiller'}).click();
  await calendar.locator('[data-aml-calendar-day="2028-02-29"]').click();
  const stepped = page.locator('[data-aml-calendar]').filter({has: page.locator('#stepped')});
  await expect(stepped.locator('[data-aml-calendar-day="2028-02-27"]')).toBeDisabled();
  await stepped.locator('[data-aml-calendar-day="2028-02-28"]').focus();
  await page.keyboard.press('ArrowLeft');
  await expect(stepped.locator('[data-aml-calendar-day="2028-02-26"]')).toBeFocused();
  await page.keyboard.press('ArrowRight'); await page.keyboard.press('ArrowRight');
  await expect(stepped.locator('[data-aml-calendar-day="2028-03-01"]')).toBeFocused();
  await page.keyboard.press('Space');
  await expect(page.locator('#stepped')).toHaveValue('2028-03-01');
  await page.locator('[name="child-country"]').selectOption('CA');
  await expect(page.locator('#country')).toHaveValue('CA');
  await page.locator('#priority').selectOption('1');
  await expect(page.locator('#priority-value')).toHaveText('integer:1');
  await page.getByRole('button', {name: 'Afficher ou masquer'}).click();
  await expect(calendar).toBeHidden();
  await page.getByRole('button', {name: 'Afficher ou masquer'}).click();
  await expect(calendar.getByRole('grid')).toBeVisible();
  await page.getByRole('button', {name: 'Effacer', exact: true}).click();
  await expect(page.locator('#date')).toHaveValue('');
  await expect(calendar.locator('[aria-selected="true"]')).toHaveCount(0);
  await page.getByRole('button', {name: 'Enregistrer', exact: true}).click();
  await expect(page.locator('#date')).toHaveAttribute('aria-invalid', 'true');
  const readonly = page.locator('[data-aml-calendar]').filter({has: page.locator('#readonly-date')});
  expect(await readonly.locator('button').evaluateAll(buttons => buttons.every(button => button.disabled))).toBe(true);
  expect(errors).toEqual([]);
});

test('styled controls work through navigation, form submission and mobile layout', async ({page}, testInfo) => {
  test.setTimeout(60_000);
  await page.goto(taskBaseURL + '/settings');
  await expect(page.locator('[data-aml-engine-mounted="true"]').first()).toBeVisible();
  await page.evaluate(() => { window.controlsDocument = true; });
  await page.getByRole('link', {name: 'Picker, Toggle et calendrier'}).click();
  await expect(page.getByRole('heading', {name: 'Un rendez-vous, simplement.'})).toBeVisible();
  expect(await page.evaluate(() => window.controlsDocument)).toBe(true);
  await page.locator('#style-change').click();
  await expect(page.locator('#style-greeting')).toHaveCSS('font-size', '32px');
  await expect(page.locator('#style-greeting')).toHaveCSS('color', 'rgb(8, 127, 91)');
  await expect(page.locator('#style-title')).toHaveCSS('color', 'rgb(8, 127, 91)');
  await page.locator('#country').selectOption('BE');
  await expect(page.locator('#summary-country')).toHaveText('Pays : BE');
  await page.getByRole('switch', {name: 'Recevoir un rappel'}).uncheck();
  await expect(page.locator('#summary-notifications')).toHaveText('Rappel désactivé');
  await page.locator('[data-aml-calendar-day="2028-02-29"]').click();
  await expect(page.locator('#summary-date')).toHaveText('Date : 2028-02-29');
  await page.getByRole('button', {name: 'Confirmer le rendez-vous'}).click();
  await expect(page.locator('#confirmation')).toHaveText('Rendez-vous confirmé pour le 2028-02-29.');
  await page.evaluate(() => { window.calendarAnnouncement = document.querySelector('.aml-calendar-month'); });
  await page.getByRole('button', {name: 'Mois suivant'}).click();
  expect(await page.evaluate(() => window.calendarAnnouncement === document.querySelector('.aml-calendar-month'))).toBe(true);
  await expect(page.getByRole('button', {name: 'Mois suivant'})).toBeFocused();
  await page.locator('[data-aml-calendar-day="2028-03-29"]').focus();
  await page.keyboard.press('Home');
  await expect(page.locator('[data-aml-calendar-day="2028-03-27"]')).toBeFocused();
  await page.keyboard.press('End');
  await expect(page.locator('[data-aml-calendar-day="2028-04-02"]')).toBeFocused();
  await page.keyboard.press('PageUp');
  await expect(page.locator('[data-aml-calendar-day="2028-03-02"]')).toBeFocused();
  await page.evaluate(() => window.scrollTo({top: 0, behavior: 'instant'}));
  if (process.env.PHPAML_CONTROL_SCREENSHOTS === '1') await page.screenshot({path: testInfo.outputPath('controls-desktop.png'), fullPage: true});
  await page.setViewportSize({width: 375, height: 812});
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  if (process.env.PHPAML_CONTROL_SCREENSHOTS === '1') await page.screenshot({path: testInfo.outputPath('controls-mobile.png'), fullPage: true});
  await page.getByRole('link', {name: 'Retour aux paramètres'}).click();
  await expect(page.getByRole('heading', {name: /Settings|Paramètres/})).toBeVisible();
  await page.getByRole('link', {name: 'Picker, Toggle et calendrier'}).click();
  await expect(page.locator('#style-greeting')).toHaveCSS('font-size', '24px');
  await expect(page.locator('#style-title')).toHaveCSS('color', 'rgb(112, 71, 235)');
  await expect(page.locator('#appointment')).toHaveValue('2028-02-28');
  await expect(page.locator('[data-aml-calendar-panel]')).toHaveCount(1);
});
