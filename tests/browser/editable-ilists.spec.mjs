import {viewFile, engineTag} from './test-environment.mjs';
import {expect, test} from './runtime-test.mjs';
import {execFileSync} from 'node:child_process';
const sample = JSON.parse(execFileSync(process.env.PHP_BINARY || 'php', [viewFile('tests/editable-ilists.php'), '--json'], {encoding: 'utf8'}));

test('IList row fields, props, forms and options follow identity through changes', async ({page}) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => {
    window.listErrors = [];
    for (const name of ['aml:error', 'aml:render-error']) document.addEventListener(name, event => window.listErrors.push(event.detail.error.message), true);
  });
  await page.route('**/editable-list', route => route.fulfill({contentType: 'text/html', body: `<meta charset="utf-8"><main data-aml-client>${sample.html}</main>${engineTag}`}));
  await page.goto('/editable-list');
  await expect(page.locator('[data-aml-client]')).toHaveAttribute('data-aml-engine-mounted', 'true');
  const row = key => page.locator(`#direct > [data-aml-list-key="${key}"]`);
  const click = name => page.getByRole('button', {name, exact: true}).click();
  await expect(row('a').locator('.natural')).toHaveText('Hello Alpha');
  await expect(row('b').locator('.closure')).toHaveText('BETA');
  await row('a').getByRole('button', {name: 'Count', exact: true}).click();
  await expect(row('a').locator('.child-count')).toHaveText('1');
  await page.evaluate(() => window.savedRow = document.querySelector('#direct > [data-aml-list-key="a"]'));
  await row('a').locator('[name="name"]').focus();
  await row('a').locator('[name="name"]').evaluate(input => input.setSelectionRange(1, 3));
  await page.getByRole('button', {name: 'Reverse', exact: true}).evaluate(button => button.click());
  await expect(row('a').locator('[name="name"]')).toBeFocused();
  expect(await row('a').locator('[name="name"]').evaluate(input => [input.selectionStart, input.selectionEnd])).toEqual([1, 3]);
  await expect(page.locator('#direct > [data-aml-list-key]').first()).toHaveAttribute('data-aml-list-key', 'b');
  expect(await page.evaluate(() => window.savedRow === document.querySelector('#direct > [data-aml-list-key="a"]'))).toBe(true);
  await row('a').locator('[name="name"]').fill('Edited');
  await expect(row('a').locator('.natural')).toHaveText('Hello Edited');
  await expect(row('a').locator('.closure')).toHaveText('EDITED');
  await expect(row('a').locator('.child-name')).toHaveText('Edited');
  await expect(page.locator('#direct-component > [data-aml-list-key="a"] .child-name')).toHaveText('Edited');
  await expect(row('a').locator('.functional-name')).toHaveText('Edited');
  await expect(row('a').locator('.effect-name')).toHaveText('Edited');
  await expect(row('a').locator('.conditional')).toHaveText('Edited');
  await row('a').getByRole('button', {name: 'Functional count', exact: true}).click();
  await expect(row('a').locator('.functional-count')).toHaveText('1');
  await row('a').locator('[name="nested-name"]').first().fill('Nested edit');
  await expect(row('a').locator('.nested-text').first()).toHaveText('Nested edit');
  await expect(row('b').locator('.natural')).toHaveText('Hello Beta');
  await expect(row('a').locator('.child-count')).toHaveText('1');
  await row('a').locator('[name="child-name"]').fill('Child');
  await expect(row('a').locator('[name="name"]')).toHaveValue('Child');
  await click('Update');
  await expect(row('b').locator('.styled')).toHaveCSS('color', 'rgb(0, 136, 0)');
  await expect(row('b').locator('a')).toHaveAttribute('href', '/updated');
  await expect(row('b').locator('.visible')).toBeVisible();
  await expect(row('b').locator('.conditional')).toHaveText('Updated');
  await row('b').getByRole('switch').uncheck();
  await expect(row('b').locator('.visible')).toBeHidden();
  await page.locator('[name="query"]').fill('child');
  await expect(page.locator('#filtered > [data-aml-list-key]')).toHaveCount(1);
  await page.locator('#filtered [name="filtered-name"]').fill('Child 2');
  await expect(row('a').locator('.natural')).toHaveText('Hello Child 2');
  await row('a').getByRole('button', {name: 'Rename', exact: true}).click();
  await expect(row('a').locator('.natural')).toHaveText('Hello Child 2!');
  await click('Append');
  await expect(row('c').locator('.natural')).toHaveText('Hello Gamma');
  await expect(row('c').locator('.child-name')).toHaveText('Gamma');
  await expect(row('c').locator('.effect-name')).toHaveText('Gamma');
  await expect(row('c').locator('.functional-name')).toHaveText('Gamma');
  await expect(row('c').locator('.nested-text')).toHaveText('C-child');
  await row('c').locator('[name="nested-name"]').fill('New nested');
  await expect(row('c').locator('.nested-text')).toHaveText('New nested');
  await expect(row('a').locator('.nested-text').first()).toHaveText('Nested edit');
  await expect(row('c').locator('.styled')).toHaveCSS('color', 'rgb(102, 0, 102)');
  await row('c').locator('[name="name"]').fill('New');
  await expect(row('c').locator('.child-name')).toHaveText('New');
  await expect(row('a').locator('.child-count')).toHaveText('1');
  await click('Append another');
  await row('c').getByRole('switch').uncheck();
  await row('d').getByRole('switch').uncheck();
  await row('c').getByRole('button', {name: 'Conditional count', exact: true}).click();
  await expect(row('c').locator('.conditional-count')).toHaveText('1');
  await expect(row('d').locator('.conditional-count')).toHaveText('0');
  await click('Options');
  await expect(page.locator('ol#direct')).toHaveAttribute('start', '-2');
  await expect(page.locator('ol#direct')).toHaveAttribute('reversed', '');
  await expect(page.locator('#direct')).toHaveCSS('list-style-type', 'upper-roman');
  await expect(page.locator('#direct')).toHaveCSS('list-style-position', 'outside');
  await expect(row('a').locator('.child-count')).toHaveText('1');
  await page.locator('#readonly > [data-aml-list-key="a"] input').fill('Forbidden');
  await expect(page.locator('#readonly > [data-aml-list-key="a"] input')).toHaveValue('Child 2!');
  await expect(row('a').locator('.natural')).toHaveText('Hello Child 2!');
  expect((await page.evaluate(() => window.listErrors)).at(-1)).toContain('read-only');
  await page.evaluate(() => window.listErrors = []);
  await click('Bad option');
  await expect(page.locator('#direct')).toHaveCSS('list-style-type', 'upper-roman');
  expect((await page.evaluate(() => window.listErrors)).at(-1)).toContain('Invalid IList marker');
  await click('Recover'); await page.evaluate(() => window.listErrors = []);
  for (const [action, message] of [['Bad source', 'indexed array'], ['Bad key', 'strings or integers'], ['Bad label', 'scalar'], ['Bad duplicate', 'Duplicate']]) {
    await click(action);
    await expect(page.locator('#faulty > [data-aml-list-key]')).toHaveText(['Recovered']);
    expect((await page.evaluate(() => window.listErrors)).at(-1)).toContain(message);
  }
  await click('Recover'); await page.evaluate(() => window.listErrors = []);
  await click('Remove'); await expect(row('a')).toHaveCount(0);
  await click('Clear');
  expect(await page.evaluate(() => Object.keys(window.AMLEngine.effects(document.querySelector('[data-aml-client]'))))).toEqual([]);
  expect(await page.evaluate(() => JSON.stringify(window.AMLEngine.inspect(document.querySelector('[data-aml-client]')).components?.AML?.View?.Tests?.EditableILists?.ConditionalChild).includes('count'))).toBe(false);
  await expect(page.locator('#direct > [data-aml-list-key]')).toHaveCount(0);
  await click('Append'); await expect(row('c').locator('.natural')).toHaveText('Hello Gamma');
  await expect(row('c').locator('.child-count')).toHaveText('0');
  await expect(row('c').locator('.functional-count')).toHaveText('0');
  expect(await page.evaluate(() => window.listErrors)).toEqual([]);
  expect(errors).toEqual([]);
});
