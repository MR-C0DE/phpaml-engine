import {assetFile, viewFile} from './test-environment.mjs';
import {browserRuntime} from './runtime-source.mjs';
import {expect, test} from './runtime-test.mjs';
import {execFileSync} from 'node:child_process';
import {readFileSync} from 'node:fs';
const fixture = viewFile('tests/component-forms.php');
const sample = JSON.parse(execFileSync(process.env.PHP_BINARY || 'php', [fixture, '--json'], {encoding:'utf8', maxBuffer:16 * 1024 * 1024}));
const runtime = browserRuntime(readFileSync(assetFile('engine-0.1.0-beta.9.min.js'), 'utf8'));

test('child forms write parent state; constructor projections and direct new remain reactive', async ({page}) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.route('**/component-forms', route => route.fulfill({contentType:'text/html', headers:{'Content-Security-Policy':"default-src 'none'; img-src 'self'; script-src 'self'; style-src 'unsafe-inline'"}, body:`<meta charset="utf-8"><link rel="icon" href="/favicon.ico"><main data-aml-client>${sample.html}</main><script defer data-aml-engine src="/engine.js"></script>`}));
  await page.route('**/engine.js', route => route.fulfill({contentType:'text/javascript', body:runtime}));
  await page.addInitScript(() => { window.renderErrors = []; window.csp = []; document.addEventListener('aml:render-error', ({detail:{error}}) => window.renderErrors.push(error.message), true); document.addEventListener('securitypolicyviolation', event => window.csp.push(event.blockedURI)); });
  await page.goto('/component-forms');
  await expect(page.locator('[data-aml-client]')).toHaveAttribute('data-aml-engine-mounted','true');
  const input = name => page.locator(`[name="${name}"]`);
  const text = id => page.locator(`[data-test="${id}"]`);
  await expect(text('complex')).toHaveText('Bonjour ANDRé!');
  await input('mixed-amount').fill('2.5'); await expect(text('mixed-type')).toHaveText('double');
  await input('a-name').fill('Alice');
  for (const id of ['parent-name','a-label','raw','raw-alias','direct-return','inherited-private','raw-helper']) await expect(text(id)).toHaveText('Alice');
  await expect(input('b-name')).toHaveValue('Voisin');
  await expect(text('complex')).toHaveText('Bonjour ALICE!');
  await expect(text('hooked')).toHaveText('[Alice]');
  await input('spread-field').fill('Spread'); await expect(input('a-name')).toHaveValue('Spread');
  await input('nested-field').fill('Alice'); await expect(input('a-name')).toHaveValue('Alice');
  await input('named-field').fill('Tableau changé');
  await input('a-note').fill('Bonjour'); await expect(input('b-note')).toHaveValue('Bonjour');
  await input('a-quantity').fill('9'); await expect(input('b-quantity')).toHaveValue('9');
  await input('a-enabled').check(); await expect(input('b-enabled')).toBeChecked();
  await input('a-choice').selectOption('b'); await expect(input('b-choice')).toHaveValue('b');
  await input('a-city').fill('Laval'); await expect(input('b-city')).toHaveValue('Laval');
  await input('a-count').fill('12'); await input('a-flag').check(); await expect(input('b-count')).toHaveValue('12'); await expect(input('b-flag')).toBeChecked(); await expect(text('a-types')).toHaveText('integer/boolean');
  await input('a-local').fill('personnel'); await expect(input('b-local')).toHaveValue('local');
  await page.getByRole('button',{name:'Parent',exact:true}).click();
  await expect(input('a-name')).toHaveValue('Marie'); await expect(input('a-note')).toHaveValue('Note'); await expect(input('a-quantity')).toHaveValue('7'); await expect(input('a-city')).toHaveValue('Québec');
  await page.getByRole('button',{name:'Vide',exact:true}).click(); await expect(text('complex')).toHaveText('vide');
  expect(await page.evaluate(() => window.renderErrors)).toEqual([]);
  await input('a-name').fill('bad'); await expect(text('constructed-number')).toHaveText('0'); expect(await page.evaluate(() => window.renderErrors)).toHaveLength(1);
  await input('a-name').fill('Repaired'); await expect(text('constructed-number')).toHaveText('8'); await expect(text('nested-function')).toHaveText('8'); expect(await page.evaluate(() => window.csp)).toEqual([]); expect(errors).toEqual([]);
});
